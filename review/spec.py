#!/usr/bin/env python3
"""The review layer's registry: what is asked, where it is asked, and what it is called.

Everything else in this package reads this file and restates none of it. The
config generator learns which blocks a project carries, the exporter learns each
task's stage and address, the deployer learns titles, overlap and Data Manager
views, the decoder learns how to read a control name back, and the chat backend
learns the two control names it writes to.

That is the whole design rule here. The previous layer kept six copies of this
information -- one per script -- and they drifted: the per-family overlap was
written down twice under a comment claiming it was derived once, and a Data
Manager view was created for a task kind that no longer existed.

## One project per task kind family, never one per paper

A Label Studio project holds exactly one labeling config (`projects/models.py:198`)
and one `maximum_annotations` (`:259`). Splitting by task kind is what lets each
family carry its own UI *and* its own reviewer overlap. Papers are grouped by a
Data Manager view on `data.paper_id`; see `task-organization.md` for the
alternatives and why they lose.

## Every block is gated, including the ones that did not need to be

A `Repeater` is expanded client-side against the task's own data, and an absent
or empty key yields zero copies (`core/Tree.tsx:70-73`). So a block wrapped in
`<Repeater on="$gate_model">` renders only for a task carrying that key, and a
`required="true"` control inside it is never instantiated for any other kind and
cannot block their submission.

Every kind uses that mechanism, even the projects holding a single kind. The
uniformity is the point: "exactly one required question per task" becomes a
structural property rather than a coincidence, and one expansion, one decoder and
one sample-task builder serve all seven variants.
"""

