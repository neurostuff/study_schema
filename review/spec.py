# -- whose predictions are whose --------------------------------------------


def model_version(model: str, version: str) -> str:
    """The `model_version` the exporter stamps on every prediction it writes."""

    return f"{model or 'unknown'}@{version or 'unknown'}"


def ours(stamp: str | None) -> bool:
    """Was this prediction produced by the extraction pipeline?

    The sync deletes predictions before rewriting them, so it needs to know which
    rows are its to remove: this instance's chat backend attaches one of its own to
    every task it answers, and deleting those would destroy the exchange the
    annotation is supposed to carry.

    Identity deliberately ignores *which* model did the extracting. Matching the
    exported stamp exactly meant that re-running the extractor under a different
    model made every live prediction unrecognisable -- the stale rows were kept as
    another producer's, the new ones written beside them, and each task ended up
    with two sets of spans at two different sets of offsets.

    So the rule is the separator, and the reciprocal obligation is on `chat.py`:
    its own stamp must never contain one.
    """

    return "@" in (stamp or "")


# -- when the correction editor opens ---------------------------------------


@dataclass(frozen=True)
class Editor:
    """The visibility rule on a block's correction form.

    Every config leads with the cheap judgement: show the whole object, ask one
    question, and keep the editor shut until the answer is not "correct". At 35-50
    entities and 5-9 analyses a paper, a reviewer who must fill a form for every
    task will not finish.

    `visibleWhen` reads only choices and regions, never task data
    (`tags/visual/View.jsx:62-65`), so this is the only conditional available.
    """

    #: "unless" hides the editor while the verdict is one of `values`;
    #: "when" shows it only once the verdict is one of them;
    #: "always" declares no gate at all.
    mode: str
    values: tuple[str, ...] = ()

    @property
    def visible_when(self) -> str:
        return {"unless": "choice-unselected", "when": "choice-selected"}[self.mode]


ALWAYS = Editor("always")


# -- Data Manager views -----------------------------------------------------
#
# The Data Manager's filter operators, as its store declares them (`dm/src/stores/
# Filters/*`, the union `store.js:490` parses a saved view against). There is no
# "one of a set" operator for a string column: `in` is a numeric or date RANGE
# taking {min, max}.
#
# The operator is checked here because the server does not check it at all. A view
# carrying an unknown one is stored with HTTP 201 and only fails in the browser,
# where mobx-state-tree cannot match it against the union and throws during Data
# Manager init -- before any view is selected, so ONE bad filter in ONE view hangs
# the whole project's Data Manager on the loading animation with nothing in the
# server log. `in_list` shipped that way and took the structure project down.

OPERATORS = frozenset({
    "equal", "not_equal", "less", "greater", "less_or_equal", "greater_or_equal",
    "in", "not_in", "empty", "contains", "not_contains", "regex",
})


@dataclass(frozen=True)
class Filter:
    key: str
    operator: str
    value: Any
    type: str = "String"

    def __post_init__(self) -> None:
        if self.operator not in OPERATORS:
            raise ValueError(
                f"{self.operator!r} is not a Data Manager operator, and a view carrying "
                f"it would be accepted by the server and then break the project's Data "
                f"Manager in the browser. Use one of: {', '.join(sorted(OPERATORS))}"
            )

    def as_payload(self) -> dict[str, Any]:
        """Column format per `data_manager/serializers.py:156`."""

        return {
            "filter": f"filter:tasks:data.{self.key}",
            "operator": self.operator,
            "type": self.type,
            "value": self.value,
        }


@dataclass(frozen=True)
class View:
    title: str
    filters: tuple[Filter, ...] = ()
    columns: tuple[str, ...] = ()


#: Coordinate-bearing is the default, not a tab: an object no reported result
#: rests on is deprioritised, never hidden. Split on `yes` rather than enumerating
#: the negatives, both because there is no set-membership operator and because
#: naming only the positive keeps this from going stale as the negative vocabulary
#: grows.
BEARING = Filter("coordinate_status", "equal", "yes")
UNRELATED = Filter("coordinate_status", "not_equal", "yes")


# -- the task kinds ---------------------------------------------------------


@dataclass(frozen=True)
class Kind:
    """One judgement, asked one way.

    `name` is the gate key's suffix, the `task_kind` written into task data, the
    prefix of every control the block declares, and the segment of the review key
    -- one string, four uses, so a kind cannot half-exist.
    """

    name: str
    #: Which correction a wrong answer here can invalidate, and therefore which
    #: round it is imported in. Derived rather than chosen: 0 changes nodes and
    #: invalidates everything below, 1 changes edges or leaves, 2 reads both.
    #: See `staged-validation.md`.
    stage: int
    #: The one required question. Empty means the kind declares no verdict, which
    #: only `relationship` does -- its grid arrives pre-ticked from the extraction,
    #: so the ticks are the answer and a verdict could only ask the reviewer to
    #: restate them. Everywhere else a task can be submitted untouched, and the
    #: verdict is what separates "checked and correct" from "never looked at".
    question: str
    verdicts: Vocabulary
    editor: Editor
    #: Standing instruction, identical for every task of this kind, so it is baked
    #: into the config rather than shipped on every task. It was task data once,
    #: and every task of a family carried the same three sentences.
    guidance: str = ""
    #: The prompt above the span layer. Empty declares no layer, which only
    #: `adjudication` does -- it judges two readings, not the paper.
    span_prompt: str = ""
    #: Whether the span layer lets a reviewer name something that is not in the
    #: record. True for the kinds whose subject is an inventory of objects, so a
    #: missing Group, term or analysis is reported the same way: draw the span,
    #: pick from the list or type a name, and the object is born attached to its
    #: evidence. Deliberately off for `relationship` -- "this links to something
    #: that was never extracted" is stage 0's question, and a second route to one
    #: correction means two places to reconcile.
    naming: bool = False
    #: Heading over the per-row correction form, if the kind has one.
    rows: str = ""

    @property
    def gate(self) -> str:
        return gate(self.name)

    @property
    def verdict(self) -> str:
        return control(self.name, "verdict")

    def named(self, role: str, depth: int = 1) -> str:
        return control(self.name, role, depth)


