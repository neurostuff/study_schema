def views(project: Project) -> list[View]:
    """The Data Manager views to create for a project, in tab order.

    Derived rather than hand-listed. A project opens on its coordinate-bearing
    queue; a project carrying several kinds gets one tab each so a reviewer can
    take one kind across papers; every project ends with the remainder, because an
    object no reported result rests on is deprioritised and never dropped.

    Per-paper views are added at deploy time from the tasks actually imported.
    """

    out = [View("All tasks", (BEARING,), project.columns)]
    if len(project.kinds) > 1:
        out += [
            View(
                f"{name.capitalize()} tasks",
                (BEARING, Filter("task_kind", "equal", name)),
                project.columns,
            )
            for name in project.kinds
        ]
    out += list(project.extra_views)
    out.append(View("No reported result rests on this", (UNRELATED,), project.columns))
    return out
