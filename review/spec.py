#: One index flag per nesting depth. `{{idx}}` substitution is `String.replace`
#: with a string pattern (`core/Tree.tsx:48`), so only the first occurrence in an
#: attribute is replaced and nested Repeaters must not share a flag. Fixing the
#: flags by depth means no block has to invent a spelling, and a name carries its
#: whole address: `model_level_0_2_1` is level 1 of term 2.
FLAGS = ("{{i}}", "{{j}}", "{{k}}")


# -- the control-name grammar ----------------------------------------------
#
# `<kind>_<role>` plus one index per enclosing Repeater. Generated by `control`,
# read back by `parse_control`, and that is the only reason answers can be decoded
# at all: Label Studio stores `from_name`, so the name has to carry the address.
#
# Kind and role are lowercase letters only, which is what makes the split
# unambiguous -- everything after the second underscore is an index.

_CONTROL = re.compile(r"^(?P<kind>[a-z]+)_(?P<role>[a-z]+)(?P<indices>(?:_\d+)*)$")


def gate(kind: str) -> str:
    """The task-data key whose presence renders this kind's block."""

    return f"gate_{kind}"


def control(kind: str, role: str, depth: int = 1) -> str:
    """A control name carrying one index flag per enclosing Repeater.

    `depth` counts the Repeaters the control sits inside. It is never zero: every
    block is gated, so the gate's own flag is always present and always resolves
    to 0 -- which is what lets a `whenTagName` inside a block name a control
    declared in the same block without hardcoding an index.
    """

    if not kind.isalpha() or not role.isalpha():
        raise ValueError(
            f"control names split on underscores, so kind and role must be letters "
            f"only; got {kind!r}, {role!r}"
        )
    if not 1 <= depth <= len(FLAGS):
        raise ValueError(f"depth must be 1..{len(FLAGS)}, got {depth}")
    return "_".join([kind, role, *FLAGS[:depth]])


def instance(kind: str, role: str, *indices: int) -> str:
    """The name a control ends up with once the editor has expanded the Repeaters.

    The gate's index is always 0, because a gate array holds exactly one element;
    anything after it addresses a row. Predictions are written against these names
    and answers are read back from them, so this and `control` have to agree --
    which is why they are three lines apart.
    """

    return "_".join([kind, role, "0", *(str(index) for index in indices)])


@dataclass(frozen=True)
class Control:
    """A parsed control name: which question, about which row."""

    kind: str
    role: str
    indices: tuple[int, ...]

    @property
    def row(self) -> int | None:
        """The row this control addresses, or None for a block-level control.

        Index 0 is the gate's, which is always 0 and never addresses anything.
        """

        return self.indices[1] if len(self.indices) > 1 else None


def parse_control(name: str) -> Control | None:
    """Read a stored `from_name` back into (kind, role, indices).

    Returns None for anything this grammar did not generate -- `comment`, the
    object tag, and the chat controls, whose `chat_q` reads as a kind and a role
    until the kind is checked against the register. Checking it there is what keeps
    the decoder from needing a list of exceptions to skip.
    """

    match = _CONTROL.match(name or "")
    if not match or match.group("kind") not in BY_NAME:
        return None
    indices = match.group("indices")
    return Control(
        kind=match.group("kind"),
        role=match.group("role"),
        indices=tuple(int(part) for part in indices.split("_")[1:]) if indices else (),
    )


