# -- the projects -----------------------------------------------------------


@dataclass(frozen=True)
class Project:
    """One labeling config, one overlap policy, one import queue.

    `name` names the config file (`<name>.xml`) and the exported task file
    (`<paper>.tasks_<name>.json`), so those two cannot drift from each other or
    from the project they belong to.
    """

    name: str
    title: str
    description: str
    #: `maximum_annotations`. Differs per family on purpose: the value family is
    #: ~95% of the volume and wants one reviewer plus a priority-0 second pass,
    #: while the structural families are 13-20 tasks a paper and are where a
    #: second opinion is informative. One project per family is what makes that
    #: choice available at all.
    overlap: int
    kinds: tuple[str, ...]
    #: Data Manager columns for this project's generated views.
    columns: tuple[str, ...]
    #: Whether the config renders the coordinate table above its blocks. Declared
    #: once for the whole project rather than per kind, and not optional: both of
    #: this project's kinds want it, and Label Studio records `table_html` as a
    #: HyperText data type the moment the config is saved, after which it admits
    #: only a string for that key -- on import and on the PATCH the sync issues. A
    #: key present on only one kind's tasks would fail the other's.
    grid: bool = False
    #: Views beyond the per-kind and coordinate-status ones every project gets.
    extra_views: tuple[View, ...] = field(default_factory=tuple)

    @property
    def config_file(self) -> str:
        return f"{self.name}.xml"

    @property
    def task_suffix(self) -> str:
        return f"tasks_{self.name}"

    def task_file(self, paper_id: str) -> str:
        return f"{paper_id}.{self.task_suffix}.json"

    @property
    def blocks(self) -> tuple[Kind, ...]:
        return tuple(BY_NAME[name] for name in self.kinds)


