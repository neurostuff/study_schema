"""Build the Python package's models and JSON Schemas from the LinkML YAML.

The YAML is the contract; everything under `src/study_schema/models/` and
`src/study_schema/jsonschema/` is generated from it by this script and committed, so a
consumer installs the package without LinkML and CI can tell when the two disagree:

    python tools/generate_models.py           # rewrite the generated files
    python tools/generate_models.py --check   # exit 1 if any is out of date
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from dataclasses import dataclass
from pathlib import Path

from study_schema import linkml

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "study_schema"


@dataclass(frozen=True)
class Contract:
    module: str
    schema: Path
    #: JSON Schema file name -> top-level class.
    roots: dict[str, str]


CONTRACTS = (
    Contract(
        module="paper_parse",
        schema=linkml.PAPER_PARSE,
        roots={
            "parsed-paper": "ParsedPaper",
            "coordinate-parse": "CoordinateParse",
        },
    ),
    Contract(
        module="extraction",
        schema=linkml.EXTRACTION,
        roots={"extraction-record": "Study"},
    ),
    Contract(
        module="storage",
        schema=linkml.STORAGE,
        roots={"storage-study": "Study"},
    ),
)


def _header(contract: Contract) -> str:
    return (
        f"# Generated by tools/generate_models.py from {contract.schema.name}.\n"
        "# Do not edit: change the YAML and regenerate.\n"
    )


def _view(contract: Contract):
    from linkml_runtime.utils.schemaview import SchemaView

    view = SchemaView(str(contract.schema))
    view.merge_imports()
    return view


def _class_definitions(document: dict, view):
    """Each class's `$defs` entry as `(cls, definition)`."""
    classes = view.all_classes()
    for cls, definition in document["$defs"].items():
        # $defs also holds enums, which are not classes.
        if cls in classes:
            yield cls, definition


def _annotate_references(document: dict, view) -> None:
    """Mark each property that holds another entity's identifier with its target class.

    An entity is a class with an identifier slot; a reference is an induced slot whose range
    is such a class and which is not inlined.
    """
    classes = view.all_classes()
    entities = {name for name in classes if view.get_identifier_slot(name)}
    for cls, definition in _class_definitions(document, view):
        properties = definition.get("properties")
        if not properties:
            continue
        for slot in view.class_induced_slots(cls):
            if (
                slot.name in properties
                and slot.range in entities
                and not (slot.inlined or slot.inlined_as_list)
            ):
                properties[slot.name]["x-reference"] = slot.range


def _annotate_unique_keys(document: dict, view) -> None:
    """Write each class's unique keys, its own first and then inherited, as `x-unique-keys`.

    A key is a list of slot names in the order the YAML declares them. Keys are deduplicated
    by name, and the nearest declaration of a name wins, so a subclass's key replaces an
    ancestor's key of the same name.
    """
    for cls, definition in _class_definitions(document, view):
        keys: dict[str, list[str]] = {}
        for ancestor in view.class_ancestors(cls):
            for key in view.get_class(ancestor).unique_keys.values():
                keys.setdefault(key.unique_key_name, list(key.unique_key_slots))
        if keys:
            definition["x-unique-keys"] = list(keys.values())


def render() -> dict[Path, str]:
    """Every generated file, path -> contents."""
    from linkml.generators.jsonschemagen import JsonSchemaGenerator
    from linkml.generators.pydanticgen import PydanticGenerator

    out: dict[Path, str] = {}
    for contract in CONTRACTS:
        view = _view(contract)
        models = PydanticGenerator(
            view.schema, extra_fields="forbid", metadata_mode=None
        ).serialize()
        out[PACKAGE / "models" / f"{contract.module}.py"] = _header(contract) + models
        for name, top in contract.roots.items():
            document = json.loads(
                JsonSchemaGenerator(view.schema, top_class=top).serialize()
            )
            _annotate_references(document, view)
            _annotate_unique_keys(document, view)
            out[PACKAGE / "jsonschema" / f"{name}.schema.json"] = (
                json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
            )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if a generated file is out of date"
    )
    args = parser.parse_args(argv)

    stale = []
    for path, text in render().items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if args.check:
            diff = difflib.unified_diff(
                (current or "").splitlines(keepends=True),
                text.splitlines(keepends=True),
                fromfile=f"{path.relative_to(ROOT)} (committed)",
                tofile=f"{path.relative_to(ROOT)} (generated)",
                n=1,
            )
            sys.stdout.writelines(list(diff)[:40])
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

    for path in stale:
        verb = "out of date" if args.check else "wrote"
        print(f"{verb}: {path.relative_to(ROOT)}")
    if args.check and stale:
        print("run: python tools/generate_models.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
